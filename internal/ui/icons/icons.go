// Show them with ui.Icon, which colors and sizes them as text.
package icons

import (
	"embed"

	"github.com/egoist/mygo/ui"
)

//go:embed lucide/*.svg
var files embed.FS

func parse(name string) *ui.SVG {
	data, err := files.ReadFile("lucide/" + name + ".svg")
	if err != nil {
		panic(err)
	}
	return ui.MustParseSVG(data)
}

